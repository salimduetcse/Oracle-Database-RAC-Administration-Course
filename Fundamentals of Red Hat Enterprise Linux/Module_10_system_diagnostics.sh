############## Basic troubleshooting ##########
# journalctl : journalctl is a Linux command used to view and analyze logs collected by systemd-journald.
# It provides centralized logging and allows filtering by service, boot, priority, time, PID, and more.
Architecture of journalctl has two Components: 
1. systemd-journald : Service that collects logs, Stores logs in binary format
2. journalctl : Command-line tool to read logs
# check the journalctl service

[root@salimapp ~]# systemctl status systemd-journald

Where logs are stored?
1. Temporary logs (RAM)
[root@salimapp ~]# /run/log/journal/
2. Persistent logs (Disk)
[root@salimapp ~]# /var/log/journal/

If persistent logs are not enabled:

[root@salimapp ~]# mkdir -p /var/log/journal
[root@salimapp ~]# systemd-tmpfiles --create --prefix /var/log/journal
[root@salimapp ~]# systemctl restart systemd-journald

# Basic Journalctl commands 
1. Live log monitoring (real-time)
[root@salimapp ~]# journalctl -f
2. Show recent boot logs Previous boot logs
[root@salimapp ~]# journalctl -b
3. Previous boot logs
[root@salimapp ~]# journalctl -b -1
4. Logs for a service- Example: SSH service
[root@salimapp ~]# journalctl -u sshd
5. Logs by time/date : Since today
[root@salimapp ~]# journalctl --since today | journalctl --since "1 hour ago" | journalctl --since "2026-05-17 10:00:00"
Last hour
[root@salimapp ~]# journalctl --since "1 hour ago"
Specific time
[root@salimapp ~]# journalctl --since "2026-05-17 10:00:00"
Between times
[root@salimapp ~]# journalctl --since "09:00" --until "11:00"
6. Recent Kernel log
[root@salimapp ~]# journalctl -k -b
7. Disk usage of logs : Check journal size:
[root@salimapp ~]# journalctl --disk-usage

